"""Connect app.votv.host to Cobalt.

- Shell: before Cobalt's own addInterface call -> Host.onInjector(injector) adds window.VotHost
- Shell: after StartupGuardNavigationObserver(webContents) -> Host.onWebContents(webContents)
- NavObserver: a WebContentsObserver subclass generated here, because the observer base
  class has an obfuscated name (found as the superclass of StartupGuardNavigationObserver)
- manifest: allow cleartext HTTP (the host itself only allows it for the dev server)
- assets/votv/bundle.js: the plugins shipped with the APK
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from . import Ctx, PatchError

SHELL = "Ldev/cobalt/shell/Shell;"
GUARD = "Ldev/cobalt/shell/StartupGuardNavigationObserver;"
WC = "Lcobalt/org/chromium/content_public/browser/WebContents;"
NAV = "Lcobalt/org/chromium/content_public/browser/NavigationHandle;"
HOST = "Lapp/votv/host/Host;"


def _hook_shell(ctx: Ctx) -> None:
    path = ctx.class_file(SHELL)
    text = path.read_text(encoding="utf-8")

    # 1) addInterface(long ptr, injector, object, name, annotation, origins): ptr is wide,
    #    so the injector is the register right after the pair.
    add = re.compile(
        r"^(\s*)invoke-static/range \{v(\d+) \.\. v\d+\}, Lorg/jni_zero/GEN_JNI;->"
        r"cobalt_org_chromium_content_browser_JavascriptInjectorImpl_addInterface\(", re.M)
    hits = list(add.finditer(text))
    if len(hits) != 1:
        raise PatchError(f"addInterface call in Shell: expected 1, got {len(hits)}")
    m = hits[0]
    reg = int(m.group(2)) + 2
    if reg > 15:
        raise PatchError(f"injector register v{reg} too high for invoke-static")
    hook = f"{m.group(1)}invoke-static {{v{reg}}}, {HOST}->onInjector(Ljava/lang/Object;)V\n\n"
    text = text[: m.start()] + hook + text[m.start():]

    # 2) new StartupGuardNavigationObserver(webContents)
    obs = re.compile(
        r"^(\s*)invoke-direct \{[vp]\d+, ([vp]\d+)\}, " + re.escape(GUARD) + r"-><init>\(" + re.escape(WC) + r"\)V\n",
        re.M)
    hits = list(obs.finditer(text))
    if len(hits) != 1:
        raise PatchError(f"StartupGuardNavigationObserver construction: expected 1, got {len(hits)}")
    m = hits[0]
    hook = f"\n{m.group(1)}invoke-static {{{m.group(2)}}}, {HOST}->onWebContents(Ljava/lang/Object;)V\n"
    text = text[: m.end()] + hook + text[m.end():]

    path.write_text(text, encoding="utf-8", newline="\n")
    ctx.note(f"Shell: onInjector (v{reg}) + onWebContents hooks")


def _nav_observer(ctx: Ctx) -> None:
    guard = ctx.class_file(GUARD).read_text(encoding="utf-8")
    sup = re.search(r"^\.super (L[^;]+;)", guard, re.M).group(1)
    base = ctx.class_file(sup).read_text(encoding="utf-8")
    needed = [
        f".method public constructor <init>({WC})V",
        ".method public primaryMainDocumentElementAvailable()V",
        f".method public didFinishNavigationInPrimaryMainFrame({NAV})V",
        ".method public webContentsDestroyed()V",
    ]
    for n in needed:
        if n not in base:
            raise PatchError(f"observer base {sup} lacks: {n}")

    smali = f""".class public final Lapp/votv/host/NavObserver;
.super {sup}
.source "NavObserver.smali"

# Generated by patches/host_bridge.py: forwards page lifecycle events to Host.

.method public constructor <init>({WC})V
    .locals 0
    invoke-direct {{p0, p1}}, {sup}-><init>({WC})V
    return-void
.end method

.method public primaryMainDocumentElementAvailable()V
    .locals 0
    invoke-static {{}}, {HOST}->onDocument()V
    return-void
.end method

.method public didFinishNavigationInPrimaryMainFrame({NAV})V
    .locals 0
    invoke-static {{}}, {HOST}->onNavigation()V
    return-void
.end method

.method public webContentsDestroyed()V
    .locals 0
    invoke-static {{}}, {HOST}->onWebContentsDestroyed()V
    return-void
.end method
"""
    # Put it next to the smallest existing smali dir to keep dex sizes balanced.
    target = min(ctx.root.glob("smali*"), key=lambda d: sum(1 for _ in d.rglob("*.smali")))
    out = target / "app" / "votv" / "host" / "NavObserver.smali"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(smali, encoding="utf-8", newline="\n")
    ctx.note(f"NavObserver extends {sup} -> {target.name}")


def _manifest(ctx: Ctx) -> None:
    mf = ctx.manifest()
    text = mf.read_text(encoding="utf-8")
    if "usesCleartextTraffic" not in text:
        text, n = re.subn(r"<application ", '<application android:usesCleartextTraffic="true" ', text, count=1)
        if n != 1:
            raise PatchError("<application> not found")
    mf.write_text(text, encoding="utf-8", newline="\n")


def _assets(ctx: Ctx) -> None:
    bundle = ctx.cfg.get("_bundle")
    if not bundle or not Path(bundle).exists():
        raise PatchError("plugin bundle not built")
    dst = ctx.root / "assets" / "votv"
    dst.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(bundle, dst / "bundle.js")
    ctx.note(f"assets/votv/bundle.js ({Path(bundle).stat().st_size} bytes)")


def apply(ctx: Ctx) -> None:
    _hook_shell(ctx)
    _nav_observer(ctx)
    _manifest(ctx)
    _assets(ctx)
